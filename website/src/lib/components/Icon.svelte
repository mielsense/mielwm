<script
	lang="ts"
	module
>
	import type { IconData, IconNode } from '@/icons';

	// Stands for the instance's id prefix in cached markup, so masks get ids unique on the page.
	const ID = '\u0000';

	// Attribute keys may be camelCase (`strokeWidth`); they are written out kebab-cased.
	const kebab = (key: string) => key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
	const escape = (value: string | number) =>
		String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

	function serialize(list: readonly IconNode[], strokeWidth: number | undefined): string {
		let markup = '';
		for (const [tag, source, children] of list) {
			let attributes = '';
			let stroked = false;
			let filled = false;
			for (const [key, raw] of Object.entries(source)) {
				if (key === 'key') continue;
				const name = kebab(key);
				stroked ||= name === 'stroke';
				filled ||= name === 'fill';
				let value = name === 'stroke-width' && strokeWidth !== undefined ? strokeWidth : raw;
				if (typeof value === 'string' && value.includes('@')) {
					value =
						name === 'id'
							? value.replace('@', `${ID}-`)
							: value.replace(/url\(@(\w+)\)/g, `url(#${ID}-$1)`);
				}
				attributes += ` ${name}="${escape(value)}"`;
			}
			// The <svg> fills with currentColor for glyphs. A stroked element without its own fill is a line.
			if (stroked && !filled) attributes += ' fill="none"';
			markup += `<${tag}${attributes}>${children ? serialize(children, strokeWidth) : ''}</${tag}>`;
		}
		return markup;
	}

	const cache = new WeakMap<IconData, Map<number | undefined, string>>();

	/** An icon's inner markup, built once per icon and stroke width. */
	function markupFor(icon: IconData, strokeWidth: number | undefined): string {
		let byWidth = cache.get(icon);
		if (!byWidth) cache.set(icon, (byWidth = new Map()));
		let markup = byWidth.get(strokeWidth);
		if (markup === undefined) byWidth.set(strokeWidth, (markup = serialize(icon, strokeWidth)));
		return markup;
	}
</script>

<script lang="ts">
	import type { SVGAttributes } from 'svelte/elements';

	type Props = SVGAttributes<SVGSVGElement> & {
		icon: IconData;
		/** Width and height in pixels. */
		size?: number | string;
		/** Overrides the stroke width of line icons. */
		strokeWidth?: number;
		/** Bindable reference to the `<svg>`. */
		element?: SVGSVGElement | null;
	};

	let { icon, size = 16, strokeWidth, element = $bindable(null), class: className, ...rest }: Props = $props();

	// Masks need ids unique on the page. `$props.id()` matches between the server and the browser.
	const uid = $props.id();

	// The drawing is generated by this package, never user input, so it goes in as markup: one
	// node for Svelte to manage instead of an element and an attribute effect per SVG part.
	const markup = $derived(markupFor(icon, strokeWidth).replaceAll(ID, uid));
</script>

<svg
	bind:this={element}
	xmlns="http://www.w3.org/2000/svg"
	width={size}
	height={size}
	viewBox="0 0 24 24"
	fill="currentColor"
	aria-hidden={rest['aria-label'] ? undefined : 'true'}
	focusable="false"
	class={['shrink-0', className]}
	{...rest}
>
	{@html markup}
</svg>
